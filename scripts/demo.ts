// Phase 0 acceptance journey (docs/12) end to end through the HTTP API.
// Synthetic data only. Run: npm run demo
import { mkdtempSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { start, importCohort, accountByExt } from '../tests/helpers.ts';
import { all, one } from '../server/db/db.ts';
import { tick } from '../server/services/outbox.ts';
import { setFault } from '../server/connectors/executors.ts';
import { verifyChain } from '../server/services/audit.ts';

const step = (n: number, s: string) => console.log(`\n${n}. ${s}`);
const ok = (s: string) => console.log(`   ✓ ${s}`);
function expect(cond: unknown, s: string) { if (!cond) { console.error(`   ✕ ${s}`); process.exit(1); } ok(s); }

const dbPath = join(mkdtempSync(join(tmpdir(), 'ar-demo-')), 'demo.db');
let h = await start(dbPath);
const ana = await h.as('u_ana');
const rui = await h.as('u_rui');

step(1, 'Import the synthetic cohort');
const imp = await importCohort(ana);
expect(imp.summary.accepted === 10, `${imp.summary.accepted} accounts imported, batch ${imp.batchId}`);

step(2, 'Open SYN-1046 and investigate: evidence collected, facts resolved, DED01 evaluated');
const id = await accountByExt(ana, 'SYN-1046');
const first = (await ana.post(`/api/accounts/${id}/investigate`)).body;
expect(first.actionId, `proposal ${first.actionId}: ${first.outcome} at revision ${first.accountRevision}`);

step(3, 'A simulated payer call contradicts the accumulator; the proposal is superseded');
const call = (await ana.post(`/api/accounts/${id}/calls/simulate`)).body;
expect(call.outcome === 'specialist_review' && call.reasonCodes.includes('SOURCE_CONFLICT'), `rule abstains: ${call.reasonCodes.join(', ')}`);
expect(call.superseded.includes(first.actionId), 'earlier proposal marked superseded');
const staleTry = await rui.post(`/api/actions/${first.actionId}/review`, { decision: 'approved', rationale: 'Approving the old one', payloadSha256: (await ana.get(`/api/accounts/${id}`)).body.actions.find((a: any) => a.actionId === first.actionId).payloadSha256, accountRevision: first.accountRevision });
expect(staleTry.status === 409, `approving the stale proposal is refused (${staleTry.body.error.code})`);

step(4, 'Reviewer corrects the conflicting fact with a reason; a new proposal is generated');
let v = (await rui.get(`/api/accounts/${id}`)).body;
const fixed = (await rui.post(`/api/accounts/${id}/facts/metBeforeCents/correct`, { value: 120000, reason: 'Adjudication-time accumulator snapshot is authoritative; rep quoted today\'s total', expectedRevision: v.account.revision })).body;
expect(fixed.actionId, `new proposal ${fixed.actionId}: ${fixed.outcome} at revision ${fixed.accountRevision}`);

step(5, 'A different reviewer is required: the proposal was generated by the correcting reviewer');
v = (await rui.get(`/api/accounts/${id}`)).body;
const act = v.actions[0];
const self = await rui.post(`/api/actions/${act.actionId}/review`, { decision: 'approved', rationale: 'Self approval attempt', payloadSha256: act.payloadSha256, accountRevision: v.account.revision });
expect(self.status === 403, 'self-approval refused (separation of duties)');

step(6, 'Use SYN-1042 for the payer-facing path. Approve the exact payload hash');
const id2 = await accountByExt(ana, 'SYN-1042');
await ana.post(`/api/accounts/${id2}/investigate`);
const v2 = (await rui.get(`/api/accounts/${id2}`)).body;
const act2 = v2.actions[0];
const appr = await rui.post(`/api/actions/${act2.actionId}/review`, { decision: 'approved', rationale: 'Accumulator met before claim; EOB applied $425', payloadSha256: act2.payloadSha256, accountRevision: v2.account.revision });
expect(appr.status === 200, `approved; idempotency key ${appr.body.idempotencyKey}`);

step(7, 'Dispatch hits a timeout after the payer accepted (simulated fault)');
setFault(h.db, 'timeout_after_success', 1);
const t1 = tick(h.db);
expect(t1.uncertain === 1, 'outbox marked uncertain; account shows Receipt uncertain');

step(8, 'Restart the API and worker on the same database');
await h.close(); h.db.close();
h = await start(dbPath);
ok('restarted');

step(9, 'Reconcile by read-back: the receipt is found, nothing is resubmitted');
const t2 = tick(h.db);
const o = one<{ state: string; attempts: number; external_reference: string }>(h.db, 'SELECT state, attempts, external_reference FROM action_outbox')!;
expect(t2.reconciled === 1 && o.state === 'accepted', `outbox ${o.state}, reference ${o.external_reference}`);
expect(o.attempts === 1 && all(h.db, 'SELECT * FROM sim_payer_requests').length === 1, 'exactly one submission reached the payer');

step(10, 'Export the audit packet');
const ada = await h.as('u_ada');
const pkt = (await ada.get(`/api/accounts/${id2}/audit-export`)).body;
expect(pkt.auditChain.ok && verifyChain(h.db, 'tn_demo').ok, `chain verified over ${pkt.auditChain.events} events; packet sha256 ${pkt.packetSha256.slice(0, 16)}…`);
console.log('\nAll Phase 0 acceptance steps passed on synthetic data. No real data, calls or external actions.');
await h.close();
