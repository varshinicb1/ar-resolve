// AR Resolve stress / load / resilience harness (ADR 0095).
//
//   npm run stress            full mode (1k / 10k / 50k accounts, 5-minute soak)
//   npm run stress:quick      quick mode for CI (1k / 5k accounts, 20-second soak)
//   npm run stress -- --only=hostile,approvals
//
// Every scenario starts the real server (and, where relevant, standalone workers) as
// child processes against a fresh temporary SQLite file and drives the real HTTP API.
// Synthetic data only. Nothing here calls an external service.
// Results: docs/stress/runs/<mode>.json and docs/stress/runs/<mode>.md (measured values only).
import { mkdirSync, writeFileSync } from 'node:fs';
import { availableParallelism, cpus, totalmem, release } from 'node:os';
import { performance } from 'node:perf_hooks';
import { ROOT } from './lib/proc.ts';
import type { Ctx, Mode, ScenarioResult, Scenario } from './lib/ctx.ts';
import { scale } from './scenarios/scale.ts';
import { investigations } from './scenarios/investigations.ts';
import { approvals } from './scenarios/approvals.ts';
import { crash } from './scenarios/crash.ts';
import { hostile } from './scenarios/hostile.ts';
import { voice } from './scenarios/voice.ts';
import { isolation } from './scenarios/isolation.ts';
import { soak } from './scenarios/soak.ts';

const SCENARIOS: Scenario[] = [hostile, investigations, approvals, crash, voice, isolation, scale, soak];

const args = process.argv.slice(2);
const mode: Mode = args.includes('--quick') ? 'quick' : 'full';
const only = args.find((a) => a.startsWith('--only='))?.slice(7).split(',').filter(Boolean);
const selected = only ? SCENARIOS.filter((s) => only.includes(s.name)) : SCENARIOS;
if (only && selected.length !== only.length) { console.error(`Unknown scenario in --only. Known: ${SCENARIOS.map((s) => s.name).join(', ')}`); process.exit(2); }

const machine = {
  nproc: availableParallelism(), cpuModel: cpus()[0]?.model ?? 'unknown', totalMemoryMb: Math.round(totalmem() / 1048576),
  node: process.version, kernel: release(), platform: process.platform,
};
const command = `npm run ${mode === 'quick' ? 'stress:quick' : 'stress'}${only ? ` -- --only=${only.join(',')}` : ''}`;
console.log(`[stress] mode=${mode} scenarios=${selected.map((s) => s.name).join(',')} machine=${JSON.stringify(machine)}`);

const results: ScenarioResult[] = [];
for (const s of selected) {
  const r: ScenarioResult = { name: s.name, title: s.title, durationMs: 0, metrics: {}, checks: [], notes: [], error: null };
  const ctx: Ctx = {
    mode,
    log: (...m: unknown[]) => console.log(`[${s.name}]`, ...m),
    metric: (k, v) => { r.metrics[k] = v; console.log(`[${s.name}] ${k} = ${JSON.stringify(v)}`); },
    check: (name, pass, detail) => { r.checks.push({ name, pass, detail: detail ?? null }); console.log(`[${s.name}] ${pass ? 'PASS' : 'FAIL'} ${name}${detail ? ` (${detail})` : ''}`); },
    note: (t) => { r.notes.push(t); },
  };
  const t0 = performance.now();
  try { await s.run(ctx); } catch (err) { r.error = (err as Error).stack ?? String(err); console.error(`[${s.name}] ERROR`, err); }
  r.durationMs = Math.round(performance.now() - t0);
  results.push(r);
}

const failed = results.filter((r) => r.error || r.checks.some((c) => !c.pass));
const report = { mode, command, startedAt: new Date().toISOString(), machine, results, failed: failed.map((f) => f.name) };
const outDir = `${ROOT}docs/stress/runs`;
mkdirSync(outDir, { recursive: true });
const suffix = only ? `${mode}-${only.join('-')}` : mode;
writeFileSync(`${outDir}/${suffix}.json`, JSON.stringify(report, null, 2) + '\n');
writeFileSync(`${outDir}/${suffix}.md`, markdown(report));
console.log(`[stress] wrote docs/stress/runs/${suffix}.{json,md}; ${failed.length ? `FAILED: ${failed.map((f) => f.name).join(', ')}` : 'all checks passed'}`);
process.exit(failed.length ? 1 : 0);

function markdown(rep: typeof report): string {
  const lines = [`# Stress run: ${rep.mode}`, '', `Command: \`${rep.command}\``, '', `Machine: ${rep.machine.nproc} CPUs (${rep.machine.cpuModel}), ${rep.machine.totalMemoryMb} MB RAM, Node ${rep.machine.node}, ${rep.machine.platform} ${rep.machine.kernel}`, '',
    'Generated by scripts/stress/run.ts. Every value below was measured in this run.', ''];
  for (const r of rep.results) {
    lines.push(`## ${r.name}: ${r.title}`, '', `Duration ${(r.durationMs / 1000).toFixed(1)} s. ${r.error ? '**ERROR**' : r.checks.every((c) => c.pass) ? 'All checks passed.' : '**Checks failed.**'}`, '');
    if (r.checks.length) { lines.push('| Check | Result | Detail |', '|---|---|---|'); for (const c of r.checks) lines.push(`| ${c.name} | ${c.pass ? 'pass' : '**FAIL**'} | ${(c.detail ?? '').replace(/\|/g, '/')} |`); lines.push(''); }
    lines.push('```json', JSON.stringify(r.metrics, null, 1), '```', '');
    for (const n of r.notes) lines.push(`- ${n}`);
    if (r.error) lines.push('', '```', r.error, '```');
    lines.push('');
  }
  return lines.join('\n');
}
