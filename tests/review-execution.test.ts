test('worker crash mid-dispatch survives restart without duplicate submission', async () => {
  const dir = mkdtempSync(join(tmpdir(), 'ar-'));
  const path = join(dir, 'ar.db');
  const h1 = await start(path);
  const { rui, v, act } = await proposed(h1);
  await approve(rui, act, v.account.revision);
  // Simulate the worker dying after the payer received the request but before
  // recording it: claim the row, call the connector, never write the receipt.
  run(h1.db, `UPDATE action_outbox SET state='dispatching', attempts=1, lease_until='2000-01-01T00:00:00.000Z'`);
  const o = one<{ idempotency_key: string }>(h1.db, 'SELECT idempotency_key FROM action_outbox')!;
  run(h1.db, `INSERT INTO sim_payer_requests VALUES (?, 'SIM-REQ-CRASH', ?, 'clarify_allocation', '2026-10-08T00:00:00Z', 'accepted')`, o.idempotency_key, act.payloadSha256);
  await h1.close();
  h1.db.close();

  const h2 = await start(path);
  try {
    const r = tick(h2.db);
    assert.equal(r.recovered, 1);
    assert.equal(r.reconciled, 1);
    const row = one<{ state: string; external_reference: string; attempts: number }>(h2.db, 'SELECT state, external_reference, attempts FROM action_outbox')!;
    assert.deepEqual([row.state, row.external_reference, row.attempts], ['accepted', 'SIM-REQ-CRASH', 1]);
    assert.equal(all(h2.db, 'SELECT * FROM sim_payer_requests').length, 1);
  } finally { await h2.close(); }
});

